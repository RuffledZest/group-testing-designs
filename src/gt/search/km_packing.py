"""(v, k, 1) packings with a prescribed cyclic automorphism (Kramer-Mesner style), by SAT.

A packing is a set of k-subsets (blocks) of [v] in which every pair of points lies in at most one
block. We prescribe a permutation sigma of [v] (or several, generating a group G; then <sigma>
below means G) and look only for packings that are unions of
<sigma>-orbits of blocks. Choosing orbit O_j (indicator x_j) covers every pair of its blocks; the
packing condition becomes, for every pair orbit P (represented by one pair p):
    sum_j  mult_j(p) * x_j <= 1,
where mult_j(p) is the number of blocks of O_j containing p (an orbit with mult >= 2 for some
pair is never a packing and is dropped). Since sigma maps pairs of P bijectively, checking one
representative per pair orbit is enough. We ask for at least ``blocks`` blocks in total, as a
cardinality constraint over orbits of equal size (only full-length orbits are used, so
sum x_j >= ceil(blocks / |orbit|)).

Every result is re-checked directly (all pairs at most once) by ``is_packing``.
"""

from __future__ import annotations

import time
from itertools import combinations
from math import ceil

from pysat.card import CardEnc, EncType
from pysat.formula import CNF, IDPool
from pysat.solvers import Solver


def is_packing(blocks, v: int) -> bool:
    seen = set()
    for b in blocks:
        if len(set(b)) != len(b) or min(b) < 0 or max(b) >= v:
            return False
        for p in combinations(sorted(b), 2):
            if p in seen:
                return False
            seen.add(p)
    return True


def cyclic_sigma(orbits: list[int], fixed: int) -> list[int]:
    """sigma = product of cycles of the given lengths on consecutive points, then ``fixed`` fixed points."""
    sig, start = [], 0
    for L in orbits:
        sig += [start + (i + 1) % L for i in range(L)]
        start += L
    return sig + list(range(start, start + fixed))


def _gens(sig) -> list[list[int]]:
    """A single permutation, or a list of generator permutations of one group."""
    return [list(sig)] if sig and isinstance(sig[0], int) else [list(g) for g in sig]


def _orbit(block: tuple, sig) -> list[tuple]:
    """Orbit of a set under the group generated by ``sig`` (breadth-first closure)."""
    gens = _gens(sig)
    start = tuple(sorted(block))
    out, seen, todo = [start], {start}, [start]
    while todo:
        b = todo.pop()
        for g in gens:
            c = tuple(sorted(g[x] for x in b))
            if c not in seen:
                seen.add(c)
                out.append(c)
                todo.append(c)
    return out


def km_packing(v: int, k: int, blocks: int, sig, *, solver: str = "cadical195",
               time_limit: float | None = None, conf_slice: int = 50_000):
    """(status, blocks): status "SAT" with the blocks of a <sig>-invariant (v, k, 1) packing with
    >= ``blocks`` blocks, "UNSAT" (no such invariant packing from full-length orbits) or
    "UNKNOWN" (time limit)."""
    t0 = time.perf_counter()
    seen, orbits = set(), []
    for b in combinations(range(v), k):
        if b in seen:
            continue
        o = _orbit(b, sig)
        seen.update(o)
        orbits.append(o)
    full = max(len(o) for o in orbits)
    pair_rep, rep_of = {}, {}
    for p in combinations(range(v), 2):
        if p in rep_of:
            continue
        for m in _orbit(p, sig):
            rep_of[m] = p
    cover = {}  # pair rep -> list of orbit indices
    usable = []
    for o in orbits:
        if len(o) != full:
            continue
        cnt = {}
        for b in o:
            for p in combinations(b, 2):
                r = rep_of[p]
                cnt[r] = cnt.get(r, 0) + (1 if p == r else 0)
        if any(c > 1 for c in cnt.values()):
            continue
        j = len(usable)
        usable.append(o)
        for r, c in cnt.items():
            if c:
                cover.setdefault(r, []).append(j)
    pool = IDPool()
    xs = [pool.id(("x", j)) for j in range(len(usable))]
    cnf = CNF()
    for r, js in cover.items():
        if len(js) > 1:
            cnf.extend(CardEnc.atmost([xs[j] for j in js], 1, vpool=pool, encoding=EncType.seqcounter).clauses)
    need = ceil(blocks / full)
    cnf.extend(CardEnc.atleast(xs, need, vpool=pool, encoding=EncType.seqcounter).clauses)
    with Solver(name=solver, bootstrap_with=cnf.clauses) as s:
        res = None
        while res is None:
            if time_limit is not None and time.perf_counter() - t0 > time_limit:
                return "UNKNOWN", None
            s.conf_budget(conf_slice)
            res = s.solve_limited()
        if not res:
            return "UNSAT", None
        model = set(v_ for v_ in s.get_model() if v_ > 0)
    out = [b for j, o in enumerate(usable) if xs[j] in model for b in o]
    if not is_packing(out, v) or len(out) < blocks:
        raise AssertionError("SAT model is not a packing of the requested size")
    return "SAT", out
